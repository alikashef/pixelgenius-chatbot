LAYERS = [
    ("frontend", "فرانت‌اند"),
    ("backend", "بک‌اند"),
    ("database", "دیتابیس"),
    ("extras", "زیرساخت و سرویس‌ها"),
]


def render_stack_tiers(settings: dict) -> str:
    tiers = [t for t in settings.get("designer_stack_tiers") or [] if isinstance(t, dict)]
    if not tiers:
        return ""
    labels = " / ".join(str(t.get("label") or t.get("key")) for t in tiers)
    lines = [
        f"تشخیص اندازه پروژه (وظیفه‌ی خودِ توست): اندازه پروژه یکی از این‌هاست: {labels}.",
        "- از همان ابتدای گفتگو، با هر پاسخ مشتری اندازه را در ذهن خودت تخمین بزن؛ معیارها: تعداد صفحه‌ها و قابلیت‌ها، ثبت‌نام و نقش‌های کاربری، "
        "پرداخت، پنل مدیریت، حجم داده و کاربر، هوش مصنوعی یا بلادرنگ، و نیاز به رشد. اگر دو اندازه محتمل است و تفاوت استک مهم است، فقط همان را با یک سوال کوتاه روشن کن.",
        "- هر وقت اندازه مشخص شد (یا عوض شد) آن را در یک جمله کوتاه به مشتری بگو و دلیلش را بیاور؛ مثلاً «با توجه به پنل مدیریت و پرداخت، این پروژه در اندازه متوسط قرار می‌گیرد».",
        "- استک را فقط از ردیف همان اندازه در جدول زیر انتخاب کن، ولی فقط موارد موردنیاز همین پروژه را بردار (مثلاً درگاه پرداخت یا پیامک را فقط وقتی پروژه پرداخت یا پیامک دارد). ابزار بیرون از جدول فقط با دلیل مشخص و نزدیک‌ترین گزینه مجاز است.",
        "- در JSON نهایی، recommended_stack را با «اندازه پروژه: <اندازه>» شروع کن و سپس استک و دلیل را بنویس؛ در admin_summary هم اندازه و معیار تشخیص آن را بیاور.",
        "جدول استک هر اندازه (تأییدشده توسط مدیر):",
    ]
    for tier in tiers:
        parts = [f"{label}: {', '.join(tier[key])}" for key, label in LAYERS if tier.get(key)]
        lines.append(f"- {tier.get('label', tier.get('key', ''))} ({tier.get('description', '')}) → " + (" | ".join(parts) or "بدون محدودیت"))
    return "\n".join(lines)
